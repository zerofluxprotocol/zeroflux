// Generates src/generated/types.ts from the checked-in JSON Schemas in
// ../../schemas. Each schema keeps its own local `#/definitions`, so we merge
// them into one root document (erroring if two files define the same name
// differently) and compile once, which avoids duplicate type declarations.
import { compile } from 'json-schema-to-typescript';
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, '../../../schemas');
const outFile = resolve(here, '../src/generated/types.ts');

const definitions = {};
const untitled = ({ title: _t, ...rest }) => rest;
const roots = [];
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith('.json')).sort()) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), 'utf8'));
  const { definitions: defs = {}, $schema: _ignored, ...body } = schema;
  const title = body.title ?? file.replace(/\.json$/, '');
  const add = (name, def) => {
    if (name in definitions) {
      if (!isDeepStrictEqual(untitled(definitions[name]), untitled(def))) {
        throw new Error(`definition ${name} in ${file} conflicts with an earlier schema`);
      }
      if (def.title) definitions[name] = def; // prefer the titled top-level copy
      return;
    }
    definitions[name] = def;
  };
  for (const [name, def] of Object.entries(defs)) add(name, def);
  add(title, { ...body, title });
  roots.push(title);
}

const root = {
  title: 'PromptVpnSchemas',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(roots.map((t) => [t, { $ref: `#/definitions/${t}` }])),
  definitions,
};

const ts = await compile(root, 'PromptVpnSchemas', {
  bannerComment:
    '/* eslint-disable */\n/**\n * Generated by `npm run gen:types` from /schemas/*.json. Do not edit by hand.\n */',
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  style: { singleQuote: true },
});
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, ts);
console.log(`wrote ${outFile} (${roots.length} schemas: ${roots.join(', ')})`);
