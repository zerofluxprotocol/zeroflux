import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { authMessage, cancelAllMessage, cancelMessage, orderMessage, withdrawMessage, KeySigner, signB64, verify } from "../src/index.js";

const v = JSON.parse(readFileSync(new URL("./vectors.json", import.meta.url), "utf8"));
const seed = Uint8Array.from(Buffer.from(v.seed_hex, "hex"));
const signer = KeySigner.fromSeed(seed);
const byName = Object.fromEntries(v.messages.map((m: any) => [m.name, m]));

describe("wire parity with Rust (vectors.json generated by zfx-perps-client)", () => {
  it("keys", () => {
    expect(signer.publicKey).toBe(v.public_key);
    expect(signer.nearSecret).toBe(v.near_secret);
    expect(KeySigner.fromNearSecret(v.near_secret).publicKey).toBe(v.public_key);
  });

  it("messages are byte-identical", () => {
    expect(orderMessage({ account: "alice.test.near", market: "NEAR-USDC", side: "buy", price: 42500, qty: 12, tif: "gtc", stp: "cancel_taker", clientId: 7, tsMs: 1700000000000 })).toBe(byName.order.message);
    expect(cancelMessage("alice.test.near", "NEAR-USDC", 91, 0, 1700000000001)).toBe(byName.cancel.message);
    expect(cancelAllMessage("alice.test.near", null, 1700000000002)).toBe(byName.cancel_all.message);
    expect(cancelAllMessage("alice.test.near", "NEAR-USDC", 1700000000003)).toBe(byName.cancel_all_market.message);
    expect(withdrawMessage("ob.test.near", "alice.test.near", "usdc.test.near", (1n << 128n) - 1n, 3)).toBe(byName.withdraw.message);
    expect(authMessage("alice.test.near", 1700000000004)).toBe(byName.auth.message);
  });

  it("signatures are identical (ed25519 is deterministic) and verify", async () => {
    for (const m of v.messages) {
      expect(await signB64(signer, m.message)).toBe(m.signature_b64);
      expect(verify(v.public_key, m.message, m.signature_b64)).toBe(true);
      expect(verify(v.public_key, m.message + "x", m.signature_b64)).toBe(false);
    }
  });
});

import { signTsMs } from "../src/signer.js";
describe("signTsMs", () => {
  it("never repeats within a millisecond (the gateway rejects replayed signatures)", () => {
    const xs = Array.from({ length: 10_000 }, () => signTsMs());
    for (let i = 1; i < xs.length; i++) expect(xs[i]).toBeGreaterThan(xs[i - 1]);
  });
});
